#!/usr/bin/env python3
# Writes sm8250-oculus-hollywood-dtbo-sink.dtsi: one empty node per label that Meta's board overlays
# (the dtbo partition) reference, and a __symbols__ entry pointing each label there. The bootloader
# applies the overlay on top of the kernel's tree; with every label resolved into this sink, the
# overlay lands in empty nodes instead of failing or rewriting the real hardware nodes.
#
#   dtbo_sink.py dtbo_a.img > sm8250-oculus-hollywood-dtbo-sink.dtsi
import struct
import sys


def overlays(img):
    magic, _total, _hsz, esz, cnt, eoff = struct.unpack_from(">6I", img, 0)
    if magic != 0xD7B7AB1E:
        sys.exit("not an Android dtbo image")
    for i in range(cnt):
        size, off = struct.unpack_from(">2I", img, eoff + i * esz)
        yield img[off:off + size]


def fixups(fdt):
    if fdt[:4] != b"\xd0\x0d\xfe\xed":
        sys.exit("overlay is not a flattened device tree")
    off_struct, off_strings = struct.unpack_from(">II", fdt, 8)
    p, path, names = off_struct, [], set()
    while True:
        (tok,) = struct.unpack_from(">I", fdt, p)
        p += 4
        if tok == 1:
            e = fdt.index(b"\0", p)
            path.append(fdt[p:e].decode())
            p = (e + 4) & ~3
        elif tok == 2:
            path.pop()
        elif tok == 3:
            ln, no = struct.unpack_from(">II", fdt, p)
            p = (p + 8 + ln + 3) & ~3
            if path == ["", "__fixups__"]:
                e = fdt.index(b"\0", off_strings + no)
                names.add(fdt[off_strings + no:e].decode())
        elif tok == 9:
            return names


def main():
    names = set()
    for ov in overlays(open(sys.argv[1], "rb").read()):
        names |= fixups(ov)
    names = sorted(names)
    out = ["// SPDX-License-Identifier: GPL-2.0-only",
           "// Generated by kernel/linux72/dtbo_sink.py from the Quest 2's dtbo partition.",
           "", "/ {", "\thollywood-dtbo-sink {"]
    # every node gets a phandle: the bootloader's overlay code resolves a label to its node's phandle
    out += ["\t\tquest2,refs = <%s>;" % " ".join("&dtbo_%s" % n for n in names), ""]
    for n in names:
        out += ["\t\tdtbo_%s: %s {" % (n, n), "\t\t};"]
    out += ["\t};", "", "\t__symbols__ {"]
    out += ['\t\t%s = "/hollywood-dtbo-sink/%s";' % (n, n) for n in names]
    out += ["\t};", "};", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
